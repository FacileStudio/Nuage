const statusLedger = `CREATE TABLE goose_db_version (id integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
	version_id bigint NOT NULL, is_applied boolean NOT NULL, tstamp timestamp NOT NULL DEFAULT now());
INSERT INTO goose_db_version (version_id, is_applied) VALUES (0, true);`

func appliedVersions(t *testing.T, db *gorm.DB) []int64 {
	t.Helper()
	var versions []int64
	if err := db.Raw(`SELECT version_id FROM goose_db_version WHERE version_id > 0 ORDER BY id`).Scan(&versions).Error; err != nil {
		t.Fatalf("read the ledger: %v", err)
	}
	return versions
}

func columnDefault(t *testing.T, db *gorm.DB, table, column string) string {
	t.Helper()
	var value *string
	err := db.Raw(`SELECT column_default FROM information_schema.columns
		WHERE table_schema = current_schema() AND table_name = ? AND column_name = ?`, table, column).Scan(&value).Error
	if err != nil {
		t.Fatalf("read the default of %s.%s: %v", table, column, err)
	}
	if value == nil {
		return ""
	}
	return *value
}

func baselineUp(t *testing.T) string {
	t.Helper()
	raw, err := fs.ReadFile(migrations.FS, "00001_baseline.sql")
	if err != nil {
		t.Fatalf("read the baseline: %v", err)
	}
	up, _, found := strings.Cut(strings.SplitN(string(raw), "-- +goose Up", 2)[1], "-- +goose Down")
	if !found {
		t.Fatal("the baseline has no Down section")
	}
	return up
}

func assertMigrated(t *testing.T, db *gorm.DB) {
	t.Helper()
	if got := appliedVersions(t, db); !slices.Equal(got, []int64{1, 2}) {
		t.Fatalf("applied versions %v, want [1 2]", got)
	}
	if got := columnDefault(t, db, "users", "created_at"); got != "now()" {
		t.Fatalf("users.created_at default %q, want now()", got)
	}
}

// TestMigrateBuildsAnEmptyDatabase checks an empty schema reaches the latest
// version through every migration in order, and that a second boot is a no-op.
func TestMigrateBuildsAnEmptyDatabase(t *testing.T) {
	db := openScratchSchema(t)
	if err := Migrate(db); err != nil {
		t.Fatalf("migrate an empty schema: %v", err)
	}
	assertMigrated(t, db)
	if err := Migrate(db); err != nil {
		t.Fatalf("a second run is not a no-op: %v", err)
	}
	assertMigrated(t, db)
}

// TestMigrateStampsADatabaseBuiltByAutoMigrate rebuilds production's shape,
// the baseline's tables with no ledger and a row in them, and checks Migrate
// records the baseline without running it, applies the later migrations, and
// keeps the row. Running the baseline would fail on its first CREATE TABLE.
func TestMigrateStampsADatabaseBuiltByAutoMigrate(t *testing.T) {
	assertStampsLegacy(t, "")
}

// TestMigrateStampsALegacyDatabaseAfterStatus covers an operator who ran
// `migrate status` before the first boot: goose then created the ledger with
// only its version 0 sentinel, and the baseline must still be stamped rather
// than run.
func TestMigrateStampsALegacyDatabaseAfterStatus(t *testing.T) {
	assertStampsLegacy(t, statusLedger)
}

func assertStampsLegacy(t *testing.T, ledger string) {
	t.Helper()
	db := openScratchSchema(t)
	for _, statement := range []string{ledger, baselineUp(t),
		`INSERT INTO users (email, name, locale, created_at) VALUES ('ada@facile.studio', 'Ada', 'fr', '2026-01-02T03:04:05Z')`} {
		if statement == "" {
			continue
		}
		if err := db.Exec(statement).Error; err != nil {
			t.Fatalf("rebuild the legacy shape: %v", err)
		}
	}
	if columnDefault(t, db, "users", "created_at") != "" {
		t.Fatal("the legacy schema already has the defaults migration")
	}

	if err := Migrate(db); err != nil {
		t.Fatalf("migrate a legacy database: %v", err)
	}
	assertMigrated(t, db)
	var kept struct {
		Name   string
		Locale string
	}
	if err := db.Raw(`SELECT name, locale FROM users WHERE email = 'ada@facile.studio'`).Scan(&kept).Error; err != nil {
		t.Fatalf("read the row: %v", err)
	}
	if kept.Name != "Ada" || kept.Locale != "fr" {
		t.Fatalf("the existing row changed: %+v", kept)
	}
}
